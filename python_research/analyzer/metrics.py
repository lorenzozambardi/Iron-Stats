
from typing import Any

import numpy as np

from .constants import COEFF_ASSISTED, COEFF_PARTIAL, MUSCLES
from .models import WorkoutExercise


def calculate_set_tuts(
    base_reps: int,
    assisted_reps: int,
    partial_reps: int,
    rpe: float,
    concentric: float,
    shortening_pause: float,
    eccentric: float,
    lengthening_pause: float,
) -> list[float] | np.ndarray:
    """
    Calculates the Time Under Tension (TUT) for each rep in a set.
    
    The TUT for a standard rep is the sum of concentric, pauses, and eccentric phases.
    As the set approaches failure (measured by RIR = Reps In Reserve), reps become
    progressively slower. We apply a 'slowdown' modifier to the concentric phase based on the RIR:
    - RIR < 1.0 (grind): +1.60 seconds
    - 1.0 <= RIR < 2.0: +1.00 seconds
    - 2.0 <= RIR < 3.0: +0.60 seconds
    - 3.0 <= RIR < 4.0: +0.35 seconds
    - 4.0 <= RIR < 5.0: +0.15 seconds
    - RIR >= 5.0: +0.00 seconds
    
    Partial reps are assumed to take half the normal TUT.
    """
    if (base_reps + assisted_reps + partial_reps) == 0:
        return np.array([])

    base_tuts = np.array([])
    if base_reps > 0:
        j = np.arange(base_reps)
        rir = (10.0 - rpe) + (base_reps - 1 - j)
        slowdown = np.zeros(base_reps)
        slowdown[rir < 1.0] = 1.60
        slowdown[(rir >= 1.0) & (rir < 2.0)] = 1.00
        slowdown[(rir >= 2.0) & (rir < 3.0)] = 0.60
        slowdown[(rir >= 3.0) & (rir < 4.0)] = 0.35
        slowdown[(rir >= 4.0) & (rir < 5.0)] = 0.15
        base_tuts = concentric + slowdown + shortening_pause + eccentric + lengthening_pause

    base_rep_tut = concentric + shortening_pause + eccentric + lengthening_pause
    ass_tuts = np.full(assisted_reps, base_rep_tut) if assisted_reps > 0 else np.array([])
    part_tuts = np.full(partial_reps, 0.5 * base_rep_tut) if partial_reps > 0 else np.array([])

    return np.concatenate([base_tuts, ass_tuts, part_tuts])


def compute_effective_tut(
    tuts: list[float] | np.ndarray,
    base_reps: int,
    rpe: float,
) -> float:
    """Compute effective TUT continuously over fractional effective base reps plus extended reps."""
    if len(tuts) == 0:
        return 0.0
    eff_base = min(float(base_reps), max(0.0, float(rpe) - 4.0))
    full_eff = int(eff_base)
    frac = eff_base - full_eff
    start_idx = max(0, base_reps - full_eff)
    base_tut = float(sum(tuts[start_idx:base_reps]))
    if frac > 0.0 and start_idx > 0:
        base_tut += frac * float(tuts[start_idx - 1])
    extended_tut = float(sum(tuts[base_reps:]))
    return base_tut + extended_tut


def calculate_set_fatigue(
    base_reps: int,
    assisted_reps: int,
    partial_reps: int,
    rpe: float,
    concentric: float,
    shortening_pause: float,
    eccentric: float,
    lengthening_pause: float,
    fatigue: float,
    load_coeff: float = 1.0,
    tuts: list[float] | np.ndarray | None = None,
) -> float:
    """
    Calculates the total fatigue generated by a set.

    Fatigue is proportional to Time Under Tension (TUT), the exercise's intrinsic
    fatigue rating (`fatigue`), and an exponential RPE multiplier. (`load_coeff`
    is retained in the signature for API compatibility; it scales weighted tonnage,
    not CNS fatigue, so heavy low-coeff lifts like Squat/Deadlift are not inverted
    below isolation exercises.)
    """
    _ = load_coeff
    actual_tuts = (
        np.asarray(tuts)
        if tuts is not None and len(tuts) > 0
        else calculate_set_tuts(
            base_reps,
            assisted_reps,
            partial_reps,
            rpe,
            concentric,
            shortening_pause,
            eccentric,
            lengthening_pause,
        )
    )

    total_fat = 0.0

    if base_reps > 0 and len(actual_tuts) > 0:
        n_base = min(base_reps, len(actual_tuts))
        j = np.arange(n_base)
        rir = (10.0 - rpe) + (base_reps - 1 - j)
        rep_rpe = np.maximum(0.0, 10.0 - rir)
        rpe_mult = 1.1 ** (rep_rpe - 7.5)

        total_fat += float(np.sum(actual_tuts[:n_base] * rpe_mult)) * fatigue

    if assisted_reps > 0 and len(actual_tuts) > base_reps:
        n_ass = min(assisted_reps, len(actual_tuts) - base_reps)
        rep_rpe = 7.0
        ass_rpe_mult = 1.1 ** (rep_rpe - 7.5)
        total_fat += float(np.sum(actual_tuts[base_reps : base_reps + n_ass])) * ass_rpe_mult * fatigue * COEFF_ASSISTED

    if partial_reps > 0 and len(actual_tuts) > base_reps + assisted_reps:
        start_idx = base_reps + assisted_reps
        n_part = min(partial_reps, len(actual_tuts) - start_idx)
        part_rpe_mult = 1.0
        total_fat += float(np.sum(actual_tuts[start_idx : start_idx + n_part])) * part_rpe_mult * fatigue * (COEFF_PARTIAL / 0.5)

    return float(total_fat)


def calculate_metrics(
    workout_data: list[WorkoutExercise],
    target_session: int | None = None,
    target_week: int | None = None,
    target_macro: str | None = None,
    target_sub: str | None = None,
):
    """
    Aggregates metrics (Volume, Tonnage, Fatigue, TUT) across the parsed workout log.
    
    Can optionally filter by session, week, macro muscle group (e.g., 'Chest'), or 
    sub-muscle (e.g., 'Upper Chest'). Metrics are multiplied by the distribution 
    coefficient (Area Under Curve of the muscle profile) for accurate proportioning.
    """
    results = []
    for w_ex in workout_data:
        if target_session is not None and w_ex.session != target_session:
            continue
        ex = w_ex.exercise_obj
        if target_macro and target_macro not in {
            MUSCLES.get(sub) for sub in ex.muscles_distr
        }:
            continue
        if target_sub and target_sub not in ex.muscles_distr:
            continue
        
        def get_magnitude(val: Any) -> float:
            if isinstance(val, (int, float)):
                return float(val)
            if hasattr(val, "magnitude"):
                return float(val.magnitude)
            if isinstance(val, dict) and "magnitude" in val:
                return float(val["magnitude"])
            return 0.0

        if target_sub:
            distr_sum = get_magnitude(ex.muscles_distr.get(target_sub, 0.0))
        elif target_macro:
            distr_sum = sum(
                get_magnitude(val)
                for m, val in ex.muscles_distr.items()
                if MUSCLES.get(m) == target_macro
            )
        else:
            distr_sum = 1.0

        for w_data in w_ex.weeks:
            if target_week is not None and w_data.week_num != target_week:
                continue
            
            if not w_data.sets:
                continue

            n_sets = len(w_data.sets)
            tot_reps_arr = np.array([s.total_reps for s in w_data.sets]) * distr_sum
            eff_reps_arr = np.array([s.effective_reps for s in w_data.sets]) * distr_sum
            actual_load_arr = np.array([(s.load * ex.load_multiplier) + ex.load_offset for s in w_data.sets])
            
            vol = float(np.sum(tot_reps_arr))
            
            if vol > 0:
                ton = float(np.sum(actual_load_arr * tot_reps_arr))
                eff_ton = float(np.sum(actual_load_arr * eff_reps_arr))
                weighted_ton = ton * ex.load_coeff
                eff_weighted_ton = eff_ton * ex.load_coeff
                eff_reps = float(np.sum(eff_reps_arr))
                
                total_fat = sum(
                    (
                        s.fatigue
                        if s.fatigue > 0.0
                        else calculate_set_fatigue(
                            base_reps=s.base_reps,
                            assisted_reps=s.assisted_reps,
                            partial_reps=s.partial_reps,
                            rpe=s.rpe,
                            concentric=w_ex.concentric,
                            shortening_pause=w_ex.shortening_pause,
                            eccentric=w_ex.eccentric,
                            lengthening_pause=w_ex.lengthening_pause,
                            fatigue=ex.fatigue,
                            load_coeff=ex.load_coeff,
                            tuts=s.tuts,
                        )
                    )
                    for s in w_data.sets
                ) * distr_sum
                
                total_tut = 0.0
                effective_tut = 0.0
                for s in w_data.sets:
                    if s.total_tut > 0.0:
                        total_tut += s.total_tut
                        effective_tut += s.effective_tut
                    elif (s.base_reps + s.assisted_reps + s.partial_reps) > 0:
                        tuts = (
                            s.tuts
                            if s.tuts
                            else calculate_set_tuts(
                                base_reps=s.base_reps,
                                assisted_reps=s.assisted_reps,
                                partial_reps=s.partial_reps,
                                rpe=s.rpe,
                                concentric=w_ex.concentric,
                                shortening_pause=w_ex.shortening_pause,
                                eccentric=w_ex.eccentric,
                                lengthening_pause=w_ex.lengthening_pause,
                            )
                        )
                        total_tut += float(sum(tuts))
                        effective_tut += compute_effective_tut(tuts, s.base_reps, s.rpe)
                total_tut *= distr_sum
                effective_tut *= distr_sum
                sets_count = n_sets * distr_sum
                
                results.append(
                    {
                        "Session": w_ex.session,
                        "Name": ex.name,
                        "Week": w_data.week_num,
                        "Volume": vol,
                        "Tonnage": ton,
                        "Eff Tonnage": eff_ton,
                        "Weighted Tonnage": weighted_ton,
                        "Eff Weighted Tonnage": eff_weighted_ton,
                        "Fatigue": total_fat,
                        "Eff Reps": eff_reps,
                        "TUT": total_tut,
                        "Eff TUT": effective_tut,
                        "Sets": sets_count,
                        "session": w_ex.session,
                        "name": ex.name,
                        "week": w_data.week_num,
                        "volume": vol,
                        "tonnage": ton,
                        "effectiveTonnage": eff_ton,
                        "weightedTonnage": weighted_ton,
                        "effectiveWeightedTonnage": eff_weighted_ton,
                        "fatigue": total_fat,
                        "effectiveReps": eff_reps,
                        "totalTut": total_tut,
                        "effectiveTut": effective_tut,
                        "sets": sets_count,
                    }
                )
    return results
